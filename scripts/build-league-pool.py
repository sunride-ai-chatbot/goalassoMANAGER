#!/usr/bin/env python3
"""Write the shared league's price list: supabase/seed-league-pool.sql.

In a shared league the server owns the money, so it has to own the prices too — a price the phone sends is
not a price. This turns the game's own squad data into public.lg_pool, which lg_buy reads and lg_sell pays
70% of. Run it whenever data/ changes and re-apply the file; it replaces the table's contents in one
transaction, so a league mid-season sees new values rather than an empty pool.

The key is the one identity the built game can also compute: the club's Hebrew name, a slash, and the
player's English name — the same pair data/visuals/euro-players.json is keyed by. `qid` is deliberately not
used: src/build.py strips it, so the client could never derive it.

    python3 -I scripts/build-league-pool.py
"""
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'supabase', 'seed-league-pool.sql')
KEY_MAX = 80          # public.lg_pool.player's own check
NAME_MAX = 80


def squads():
    """(club Hebrew name, players) for every real squad the game ships."""
    for pattern in ('data/*.json', 'data/euro/*.json'):
        for path in sorted(glob.glob(os.path.join(ROOT, pattern))):
            try:
                d = json.loads(open(path, encoding='utf8').read())
            except Exception:
                continue
            club, players = d.get('name_he'), d.get('players')
            if club and isinstance(players, list):
                yield club, players


def lit(s):
    return "'" + s.replace("'", "''") + "'"


def main():
    pool, skipped, long_keys, odd_ages = {}, 0, 0, []
    for club, players in squads():
        for p in players:
            if not isinstance(p, dict):
                continue
            en, value = p.get('en'), p.get('value_m')
            # a generated player has no English name and no business in a league of real players
            if not en or not isinstance(value, (int, float)) or value <= 0:
                skipped += 1
                continue
            key = f'{club}/{en}'
            if len(key) > KEY_MAX:
                long_keys += 1
                continue
            # an age outside a footballer's range is a parse error in the source, not a fact: it is dropped
            # here rather than refused by the table's own check, which would take the whole seed down with it
            age = p.get('age')
            if not (isinstance(age, int) and 14 <= age <= 60):
                if age is not None:
                    odd_ages.append(f'{club}/{en}={age}')
                age = None
            row = (key, en[:NAME_MAX], (p.get('pos') or None), age, int(round(value * 1_000_000)))
            # the same key twice (a squad listed under two files) keeps the dearer valuation
            if key not in pool or pool[key][4] < row[4]:
                pool[key] = row

    rows = [pool[k] for k in sorted(pool)]
    with open(OUT, 'w', encoding='utf8') as f:
        f.write('-- Generated by scripts/build-league-pool.py — do not edit by hand.\n')
        f.write(f'-- {len(rows)} real players, keyed by the club\'s Hebrew name and the player\'s English name.\n')
        f.write('-- Apply after supabase/migrations/20261114210000_shared_league.sql. It replaces the whole list in\n')
        f.write('-- one transaction, so no league ever reads a half-written price table. It is too large for the\n')
        f.write('-- SQL editor to be comfortable with: apply it with `supabase db push` or psql -f.\n')
        f.write('begin;\ndelete from public.lg_pool;\n')
        for i in range(0, len(rows), 500):
            chunk = rows[i:i + 500]
            f.write('insert into public.lg_pool(player,name,pos,age,value) values\n')
            f.write(',\n'.join(
                ' (%s,%s,%s,%s,%d)' % (lit(k), lit(n), lit(pos) if pos else 'null',
                                       str(age) if isinstance(age, int) else 'null', v)
                for k, n, pos, age, v in chunk))
            f.write(';\n')
        f.write('commit;\n')

    size = os.path.getsize(OUT)
    print(f'{len(rows)} players -> {os.path.relpath(OUT, ROOT)} ({size // 1024} KB)'
          f'; skipped {skipped} without an English name or a value'
          + (f', {long_keys} keys over {KEY_MAX} characters' if long_keys else '')
          + (f'; dropped an impossible age for {", ".join(odd_ages[:5])}' if odd_ages else ''))


if __name__ == '__main__':
    main()
