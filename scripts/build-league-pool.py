#!/usr/bin/env python3
"""Write the shared league's price list: supabase/seed-league-pool.sql.

In a shared league the server owns the money, so it has to own the prices too — a price the phone sends is
not a price. This turns the game's own squad data into public.lg_pool, which lg_buy reads and lg_sell pays
70% of. Run it whenever data/ changes and re-apply the file; it replaces the table's contents in one
transaction, so a league mid-season sees new values rather than an empty pool.

The key is the one identity the built game can also compute: the club's Hebrew name, a slash, and the
player's English name — the same pair data/visuals/euro-players.json is keyed by. `qid` is deliberately not
used: src/build.py strips it, so the client could never derive it.

    python3 -I scripts/build-league-pool.py
"""
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'supabase', 'seed-league-pool.sql')
PACKED = os.path.join(ROOT, 'supabase', 'install-league-pool.sql')
KEY_MAX = 80          # public.lg_pool.player's own check
NAME_MAX = 80


def squads():
    """(club Hebrew name, players, is an Israeli top-division file) for every real squad the game ships."""
    for pattern in ('data/*.json', 'data/euro/*.json'):
        for path in sorted(glob.glob(os.path.join(ROOT, pattern))):
            try:
                d = json.loads(open(path, encoding='utf8').read())
            except Exception:
                continue
            club, players = d.get('name_he'), d.get('players')
            if club and isinstance(players, list):
                yield club, players, pattern == 'data/*.json'


def faces():
    """Who has a photograph the game will actually show: the same rule src/build.py ships to the client
    (an identity in data/visuals, and `ok` in the portrait audit). Returns (by Hebrew name, by club|English name)."""
    def load(name, fallback):
        path = os.path.join(ROOT, 'data', 'visuals', name)
        return json.loads(open(path, encoding='utf8').read()) if os.path.isfile(path) else fallback
    audit = load('portrait-audit.json', {})
    ok = lambda vid: bool(vid) and audit.get(vid, {}).get('status') == 'ok'
    il = {p['he']: p['visualId'] for p in load('players.json', {'players': []})['players'] if ok(p.get('visualId'))}
    eu_v = load('euro-players.json', {'players': [], 'faces': {}})
    eu = {p['club'] + '|' + p['en']: p['visualId'] for p in eu_v['players'] if ok(p.get('visualId')) and p['visualId'] in eu_v['faces']}
    return il, eu


def lit(s):
    return "'" + s.replace("'", "''") + "'"


def main():
    pool, skipped, long_keys, odd_ages, club_of = {}, 0, 0, [], {}
    face_il, face_eu = faces()
    for club, players, israeli in squads():
        for p in players:
            if not isinstance(p, dict):
                continue
            en, value = p.get('en'), p.get('value_m')
            # a generated player has no English name and no business in a league of real players
            if not en or not isinstance(value, (int, float)) or value <= 0:
                skipped += 1
                continue
            key = f'{club}/{en}'
            if len(key) > KEY_MAX:
                long_keys += 1
                continue
            # an age outside a footballer's range is a parse error in the source, not a fact: it is dropped
            # here rather than refused by the table's own check, which would take the whole seed down with it
            age = p.get('age')
            if not (isinstance(age, int) and 14 <= age <= 60):
                if age is not None:
                    odd_ages.append(f'{club}/{en}={age}')
                age = None
            face = bool(face_il.get(p.get('he'))) if israeli else bool(face_eu.get(club + '|' + en))
            row = (key, en[:NAME_MAX], (p.get('pos') or None), age, int(round(value * 1_000_000)), face)
            # the same key twice (a squad listed under two files) keeps the dearer valuation
            if key not in pool or pool[key][4] < row[4]:
                pool[key] = row
                club_of[key] = club

    rows = [pool[k] for k in sorted(pool)]
    with open(OUT, 'w', encoding='utf8') as f:
        f.write('-- Generated by scripts/build-league-pool.py — do not edit by hand.\n')
        f.write(f'-- {len(rows)} real players, keyed by the club\'s Hebrew name and the player\'s English name.\n')
        f.write('-- Apply after supabase/migrations/20261114210000_shared_league.sql. It replaces the whole list in\n')
        f.write('-- one transaction, so no league ever reads a half-written price table. It is too large for the\n')
        f.write('-- SQL editor to be comfortable with: apply it with `supabase db push` or psql -f.\n')
        f.write('begin;\ndelete from public.lg_pool;\n')
        for i in range(0, len(rows), 500):
            chunk = rows[i:i + 500]
            f.write('insert into public.lg_pool(player,name,pos,age,value,face) values\n')
            f.write(',\n'.join(
                ' (%s,%s,%s,%s,%d,%s)' % (lit(k), lit(n), lit(pos) if pos else 'null',
                                          str(age) if isinstance(age, int) else 'null', v, 'true' if face else 'false')
                for k, n, pos, age, v, face in chunk))
            f.write(';\n')
        f.write('commit;\n')

    # The same list once more, packed for the SQL Editor: one row of text per club instead of one row of SQL
    # per player, which is half the size and the difference between a paste that works and one that does not.
    # 'name|pos|age|value|face' joined by ';' — a name never holds either character (tests/squad-names.test.js keeps
    # wikitext out of names, and this refuses to write a file that would not read back).
    by_club = {}
    for k, n, pos, age, v, face in rows:
        club = club_of[k]                      # never split the key: a club may carry a slash of its own (בודה/גלימט)
        en = k[len(club) + 1:]
        assert '|' not in en and ';' not in en and '|' not in club and ';' not in club, k
        assert en[:NAME_MAX] == n, k
        by_club.setdefault(club, []).append('%s|%s|%s|%d|%d' % (en, pos or '', age if isinstance(age, int) else '', v, 1 if face else 0))
    with open(PACKED, 'w', encoding='utf8') as f:
        f.write('-- GOALASSO · ליגה משותפת — the price list, for the SQL Editor. Generated by scripts/build-league-pool.py.\n')
        f.write(f'-- {len(rows)} real players. Paste the whole file and press Run, after install-league.sql and install-league-2.sql (it needs both).\n')
        f.write('-- Running it again replaces the list, so it is also how the prices are refreshed.\n')
        f.write('begin;\ndelete from public.lg_pool;\n')
        f.write('insert into public.lg_pool(player,name,pos,age,value,face)\n')
        f.write("select v.c||'/'||split_part(r,'|',1), split_part(r,'|',1), nullif(split_part(r,'|',2),''), nullif(split_part(r,'|',3),'')::int, split_part(r,'|',4)::bigint, split_part(r,'|',5)='1'\n")
        f.write("from (values\n")
        f.write(',\n'.join(' (%s,%s)' % (lit(c), lit(';'.join(v))) for c, v in sorted(by_club.items())))
        f.write("\n) v(c,j), unnest(string_to_array(v.j,';')) r;\ncommit;\n")

    size = os.path.getsize(OUT)
    print(f'{len(rows)} players -> {os.path.relpath(OUT, ROOT)} ({size // 1024} KB)'
          f'; skipped {skipped} without an English name or a value'
          + (f', {long_keys} keys over {KEY_MAX} characters' if long_keys else '')
          + (f'; dropped an impossible age for {", ".join(odd_ages[:5])}' if odd_ages else '')
          + f'; packed for the SQL Editor: {os.path.relpath(PACKED, ROOT)} ({os.path.getsize(PACKED) // 1024} KB)')


if __name__ == '__main__':
    main()
