#!/usr/bin/env python3
"""Write docs/portrait-audit.md: every Israeli Premier League player, club by club, with portrait status.
Sources: data/*.json (squads), data/visuals/players.json (identities), data/visuals/portrait-audit.json (build results),
data/visuals/portrait-overrides.json (manual decisions)."""
import json, glob, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
L = lambda p: json.load(open(os.path.join(ROOT, p), encoding='utf8'))
V = L('data/visuals/players.json'); A = L('data/visuals/portrait-audit.json')
ov = L('data/visuals/portrait-overrides.json') if os.path.isfile(os.path.join(ROOT, 'data/visuals/portrait-overrides.json')) else {}
ids = {p['he']: p['visualId'] for p in V['players']}
REASON = {'source_cuts_head': 'the only available photo cuts the top of the head', 'source_is_document_scan': 'the only available photo is a scanned ID document',
          'face_too_small': 'source photo too small to enlarge cleanly', 'no_face_detected': 'no usable face in the source photo'}
uses = {}
for p in V['players']:
    uses.setdefault(p['visualId'], []).append(p['he'])
out = ['# Player portrait audit · Israeli Premier League', '',
       'Generated by `scripts/portrait-report.py`. Status `ok` = rebuilt canonical portrait shown in the game; `fallback` = the designed club-kit monogram is shown and the player is unresolved.', '']
tot = {'ok': 0, 'fallback': 0}
for f in sorted(glob.glob(os.path.join(ROOT, 'data', '*.json'))):
    c = json.load(open(f, encoding='utf8'))
    rows = []
    for r in c['players']:
        k = ids.get(r['he']); a = A.get(k, {}) if k else {}
        st = 'ok' if a.get('status') == 'ok' else 'fallback'; tot[st] += 1
        note = []
        if st == 'fallback':
            note.append(REASON.get(a.get('reason'), a.get('reason') or 'no portrait'))
        if 'informal_source' in a.get('flags', []):
            note.append('genuine but informal photo; replace when an official one exists')
        if k and len(uses.get(k, [])) > 1:
            note.append('same photo also used for: ' + ', '.join(n for n in uses[k] if n != r['he']) if any(n != r['he'] for n in uses[k]) else 'listed in two squads')
        rows.append(f"| {r['he']} | {r.get('en') or ''} | {r.get('pos') or ''} | {k or '—'} | {st} | {'; '.join(note)} |")
    ok = sum(1 for x in rows if '| ok |' in x)
    out += [f"## {c['name_he']} ({c['id']}) · {ok}/{len(rows)} portraits", '', '| Player | English | Pos | Identity | Status | Notes |', '|---|---|---|---|---|---|', *rows, '']
out.insert(4, f"**Totals:** {tot['ok']} players with a portrait, {tot['fallback']} on the designed fallback, {tot['ok'] + tot['fallback']} squad entries.\n")
os.makedirs(os.path.join(ROOT, 'docs'), exist_ok=True)
open(os.path.join(ROOT, 'docs', 'portrait-audit.md'), 'w', encoding='utf8').write('\n'.join(out) + '\n')
print(tot)
